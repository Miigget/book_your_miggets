#!/usr/bin/env node
/**
 * Parse vendored KoGmaps mapinfo.txt → supabase/seed-data/kog-maps.sql
 *
 * Re-vendor source:
 *   curl -fsSL https://raw.githubusercontent.com/Gamer12120/KoGmaps/main/mapinfo.txt \
 *     -o supabase/seed-data/kog-mapinfo.txt
 *   node scripts/import-kog-maps.mjs
 *
 * Adapted from KoGmaps mapinfo_to_json.py (pipe table, skip header/separator).
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const inputPath = join(root, "supabase/seed-data/kog-mapinfo.txt");
const outputPath = join(root, "supabase/seed-data/kog-maps.sql");

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;

function sqlLiteral(value) {
  if (value === null) return "null";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function parseReleasedOn(raw) {
  const trimmed = raw.trim();
  if (!ISO_DATE.test(trimmed)) return null;
  return trimmed;
}

function parseLength(raw) {
  const trimmed = raw.trim();
  if (trimmed === "" || trimmed === "-") return null;
  return trimmed;
}

function parseMapinfo(text) {
  const lines = text.split(/\r?\n/);
  if (lines.length < 3) {
    throw new Error("mapinfo file is too short or empty");
  }

  const maps = [];
  for (const line of lines.slice(2)) {
    if (!line.trim() || line.startsWith("=")) continue;
    const parts = line.split("|").map((p) => p.trim());
    if (parts.length < 7) continue;

    const [name, difficulty, stars, ptsRaw, lengthRaw, creator, dateRaw] = parts;
    if (!name) continue;

    const points = Number.parseInt(ptsRaw, 10);
    if (!Number.isFinite(points) || points < 0) {
      throw new Error(`Invalid points for map "${name}": ${ptsRaw}`);
    }

    maps.push({
      name,
      difficulty,
      stars,
      points,
      length: parseLength(lengthRaw),
      creator,
      released_on: parseReleasedOn(dateRaw),
    });
  }

  return maps;
}

function toSql(maps) {
  const header = `-- Generated by scripts/import-kog-maps.mjs — do not edit by hand.
-- Source: supabase/seed-data/kog-mapinfo.txt
-- Rows: ${maps.length}

`;

  const values = maps
    .map((m) => {
      return `  (${sqlLiteral(m.name)}, ${sqlLiteral(m.difficulty)}, ${sqlLiteral(m.stars)}, ${m.points}, ${sqlLiteral(m.length)}, ${sqlLiteral(m.creator)}, ${sqlLiteral(m.released_on)})`;
    })
    .join(",\n");

  return `${header}insert into public.maps (name, difficulty, stars, points, length, creator, released_on)
values
${values}
on conflict (name) do update set
  difficulty = excluded.difficulty,
  stars = excluded.stars,
  points = excluded.points,
  length = excluded.length,
  creator = excluded.creator,
  released_on = excluded.released_on,
  updated_at = now();
`;
}

const text = readFileSync(inputPath, "utf8");
const maps = parseMapinfo(text);
mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, toSql(maps), "utf8");

const nullDates = maps.filter((m) => m.released_on === null).length;
console.log(`Wrote ${maps.length} maps → ${outputPath} (${nullDates} with released_on null)`);
